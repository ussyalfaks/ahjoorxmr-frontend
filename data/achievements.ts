/** Returns the latest earned achievement badge for dashboard highlights */
export function getMostRecentEarnedBadge(): AchievementBadge | undefined {
  const earnedBadges = MOCK_ACHIEVEMENTS.filter((b) => b.earned && b.earnedAt);
  return earnedBadges.sort(
    (a, b) => new Date(b.earnedAt!).getTime() - new Date(a.earnedAt!).getTime()
  )[0];
}
